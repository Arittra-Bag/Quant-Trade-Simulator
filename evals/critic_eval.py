"""
How good is the execution agent's critic? Run it over answers the graders have already
scored and compare verdicts.

    python -m evals.critic_eval                          # recorded live answers + replay fixtures
    python -m evals.critic_eval --markdown evals/CRITIC.md

For each answer the critic sees what it would see in the agent (the order, the book, the
advice, the plans priced against the book) and either blocks it or lets it through to the
approver. The graders' verdict is the reference: an answer "should be blocked" when it
fails a check the critic is meant to enforce (side, cost grounding, depth honesty, or a
strategy the scenario rules out). No model is called.

The critic and the graders share their rules (advisor/policy.py), so agreement here shows
the critic enforces at run time what the evals measure. It is not independent evidence
that those rules are right. The scenario's `allow_strategies`/`forbid_strategies` are
judgments the critic cannot see, so an answer failing only those is counted as missed.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agent.critic import blocking, review  # noqa: E402
from agent.pricing import plans_to_price, price_plan  # noqa: E402
from evals.candidates import CANDIDATES, REAL_CANDIDATES  # noqa: E402
from evals.runner import LIVE_CANDIDATES, regrade, run_suite  # noqa: E402
from evals.scenarios import SCENARIOS, scenario_book  # noqa: E402

ENFORCED = ("side_fidelity", "cost_grounded", "depth_honesty", "strategy_allowed")
RESULTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results.json")


def critique(row, scenario):
    """The critic's findings on one recorded answer, or None when there is no advice to review."""
    if not row.get("advice"):
        return None
    order = {"side": scenario["side"], "notional": scenario["notional"],
             "fee_tier": scenario.get("fee_tier", "Tier 1"), "volatility": scenario.get("volatility", 0.01)}
    book = scenario_book(scenario)
    priced = [price_plan(order, book, p) for p in plans_to_price(row["advice"])]
    return review(order, book, row["advice"], priced)


def compare(rows):
    """One verdict per answer with advice: what the graders said and what the critic did."""
    scenarios = {s["id"]: s for s in SCENARIOS}
    out = []
    for row in rows:
        scenario = scenarios.get(row["scenario"])
        findings = critique(row, scenario) if scenario and not row.get("errored") else None
        if findings is None:
            continue
        failed = [c["name"] for c in row["checks"] if c["name"] in ENFORCED and not c["passed"]]
        blocked = blocking(findings)
        out.append({"candidate": row["candidate"], "scenario": row["scenario"], "failed": failed,
                    "blocked": list(dict.fromkeys(f["code"] for f in blocked)),
                    "warned": list(dict.fromkeys(f["code"] for f in findings if f["severity"] == "warn"))})
    return out


def tally(verdicts):
    caught = sum(1 for v in verdicts if v["failed"] and v["blocked"])
    missed = sum(1 for v in verdicts if v["failed"] and not v["blocked"])
    false_alarm = sum(1 for v in verdicts if not v["failed"] and v["blocked"])
    passed = sum(1 for v in verdicts if not v["failed"] and not v["blocked"])
    return {"answers": len(verdicts), "caught": caught, "missed": missed,
            "false_alarms": false_alarm, "let_through": passed}


def to_markdown(groups):
    out = ["# Critic eval", "",
           "The execution agent's critic run over answers the graders already scored. Generated by "
           "`python -m evals.critic_eval --markdown evals/CRITIC.md`; see that module for the method.", "",
           "| Answers | Count | Should be blocked, blocked | Should be blocked, let through | "
           "Clean, blocked (false alarm) | Clean, let through |",
           "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for label, verdicts in groups:
        t = tally(verdicts)
        out.append(f"| {label} | {t['answers']} | {t['caught']} | {t['missed']} | {t['false_alarms']} | "
                   f"{t['let_through']} |")
    for label, verdicts in groups:
        flagged = [v for v in verdicts if v["failed"] or v["blocked"]]
        out += ["", f"## {label}: every answer the graders failed or the critic blocked", ""]
        if not flagged:
            out.append("None.")
            continue
        out += ["| Candidate | Scenario | Graders failed | Critic blocked on |", "| --- | --- | --- | --- |"]
        out += [f"| `{v['candidate']}` | `{v['scenario']}` | {', '.join(v['failed']) or '-'} | "
                f"{', '.join(v['blocked']) or '-'} |" for v in flagged]
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Score the execution agent's critic.")
    parser.add_argument("--results", default=RESULTS, help="a saved run with live answers (default evals/results.json)")
    parser.add_argument("--markdown", dest="md_path")
    args = parser.parse_args(argv)

    groups = []
    if os.path.exists(args.results):
        with open(args.results) as fh:
            # Re-graded first, so a run saved under older graders is judged by today's.
            live = regrade([r for r in json.load(fh)["rows"] if r["candidate"] in LIVE_CANDIDATES])
        if live:
            groups.append(("Recorded live answers", compare(live)))
    fixtures = [n for n in CANDIDATES if n not in REAL_CANDIDATES]
    groups.append(("Replay fixtures", compare(run_suite(fixtures))))

    for label, verdicts in groups:
        t = tally(verdicts)
        print(f"{label}: {t['answers']} answers; blocked {t['caught']} of {t['caught'] + t['missed']} that "
              f"should be; {t['false_alarms']} false alarms")
    if args.md_path:
        with open(args.md_path, "w") as fh:
            fh.write(to_markdown(groups))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
