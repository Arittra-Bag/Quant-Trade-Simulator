"""
The fixed scenario set the advisor is scored on.

A scenario is one book plus one order plus the constraints a correct answer has to
satisfy. The set is deliberately small and hand-picked to cover the situations where an
execution read is easy to get wrong: an order that runs past the visible book, a wide
spread where crossing is most of the cost, a sell order (the old prompt hardcoded BUY),
and a size that nothing in the book can absorb.

Books
-----
Books live in `evals/books/*.json` and are loaded by name. The ones shipped here are
SYNTHETIC ladders generated by `make_book`, not captures from a venue, and each carries
`"synthetic": true` so nothing downstream can mistake them for recorded data. Drop a
recorded snapshot into the same directory with the same shape and the scenarios pick it
up unchanged.
"""
import json
import os

BOOKS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "books")


def make_book(mid, spread_bps, levels, top_size, growth, symbol="BTC-USDT-SWAP", source="synthetic"):
    """
    Build a symmetric ladder: `levels` per side, one tick apart, sizes growing away from
    the touch. Crude next to a real book, but it is deterministic and the characteristic
    under test (thin / deep / wide) is explicit rather than incidental.
    """
    half = mid * spread_bps / 1e4 / 2
    tick = max(round(mid * 1e-5, 8), 1e-8)
    bids, asks, size = [], [], top_size
    for i in range(levels):
        bids.append([round(mid - half - i * tick, 8), round(size, 8)])
        asks.append([round(mid + half + i * tick, 8), round(size, 8)])
        size *= growth
    return {"symbol": symbol, "source": source, "bids": bids, "asks": asks,
            "timestamp": 1758650000000, "synthetic": True}


BUILTIN_BOOKS = {
    # deep and tight: the easy case, a normal BTC book
    "deep_tight": make_book(mid=65000.0, spread_bps=0.3, levels=25, top_size=1.5, growth=1.18),
    # thin: a few hundred thousand dollars of visible depth, typical of an alt perp
    "thin": make_book(mid=1.2450, spread_bps=4.0, levels=12, top_size=8000.0, growth=1.12,
                      symbol="ARB-USDT-SWAP"),
    # wide spread, decent size: crossing is most of the cost here
    "wide": make_book(mid=3450.0, spread_bps=28.0, levels=15, top_size=2.0, growth=1.10,
                      symbol="ETH-USDT-SWAP"),
    # very shallow: nothing here can absorb size
    "shallow": make_book(mid=0.0842, spread_bps=15.0, levels=8, top_size=25000.0, growth=1.05,
                         symbol="DOGE-USDT-SWAP"),
}


def _skew(book, factor, side="bids"):
    """Return a copy of `book` with one side's sizes scaled, to create an imbalance."""
    out = {k: (list(v) if isinstance(v, list) else v) for k, v in book.items()}
    out[side] = [[p, round(s * factor, 8)] for p, s in book[side]]
    return out


BUILTIN_BOOKS["bid_heavy"] = _skew(BUILTIN_BOOKS["deep_tight"], 2.6, "bids")
BUILTIN_BOOKS["ask_heavy"] = _skew(BUILTIN_BOOKS["deep_tight"], 2.6, "asks")


def load_book(name):
    """Prefer a recorded book on disk; fall back to the built-in synthetic ladder."""
    path = os.path.join(BOOKS_DIR, f"{name}.json")
    if os.path.exists(path):
        with open(path) as fh:
            return json.load(fh)
    if name not in BUILTIN_BOOKS:
        raise KeyError(f"no book named {name!r}")
    return BUILTIN_BOOKS[name]


